export function getPalette(id?: string): ColorPalette {
  return COLOR_PALETTES.find((p) => p.id === id) || COLOR_PALETTES[0];
}

export function applyThemeVariables(paletteId: string, mode: 'dark' | 'light' = 'dark') {
  if (typeof document === 'undefined') return;
  const pal = getPalette(paletteId);
  const root = document.documentElement;

  root.style.setProperty('--color-primary', pal.primary);
  root.style.setProperty('--color-secondary', pal.secondary);
  root.style.setProperty('--color-accent', pal.accent);
  root.style.setProperty('--color-dot', pal.dotColor);

  if (mode === 'light') {
    root.style.setProperty('--app-bg', pal.bgLight);
    root.style.setProperty('--card-bg', pal.cardLight);
    root.style.setProperty('--border-color', pal.borderLight);
    root.style.setProperty('--text-primary', pal.textLight);
  } else {
    root.style.setProperty('--app-bg', '#070A0F');
    root.style.setProperty('--card-bg', '#0F141F');
    root.style.setProperty('--border-color', 'rgba(255, 255, 255, 0.1)');
    root.style.setProperty('--text-primary', '#F9FAFB');
  }
}
